// Builds src/data/wordfeather.js from Wordfeather's words_final.json
// (https://github.com/abdullahbutt/wordfeather, CC BY-NC 4.0, by Abdullah Butt).
//
//   node scripts/import-wordfeather.mjs path/to/words_final.json
//
// What we keep, so the app stays about speaking German at work and in daily life:
//   deck        B1-C2 words with a real example sentence, practised in Words mode.
//               Academic/literary register, philosophy and literature topics and
//               "Es lässt sich ..., dass ..." templates are left out.
//   dictionary  every other word (A1-A2 included), only for tap-to-translate
//               while reading, so a tapped word has a meaning to save.
// Words AchsoKumpel already has are skipped, so their ids and progress stay.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { WORDS } from '../src/data/vocabulary.js';

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/import-wordfeather.mjs path/to/words_final.json');
  process.exit(1);
}

const DECK_LEVELS = ['B1', 'B2', 'C1', 'C2'];
const SKIP_REGISTERS = new Set(['academic', 'literary']);
const SKIP_TOPICS = new Set(['Philosophie & Erkenntnistheorie', 'Sprache & Literatur']);
// C2 law and science entries are specialist terms, not conversation German.
const SKIP_C2_TOPICS = new Set(['Recht & Politik', 'Wissenschaft & Medizin']);
const WORK_TOPICS = new Set(['Arbeit & Beruf', 'Technik & Medien', 'Wirtschaft & Finanzen']);
const LEVEL_ORDER = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

// Drops invisible characters (word joiner, zero-width space, BOM) and the
// dashes our copy rules forbid: " — " becomes a comma, any other dash a hyphen.
const INVISIBLE = new RegExp('[\\u2060\\u200b\\ufeff]', 'g');
const SPACED_DASH = new RegExp('\\s+[\\u2013\\u2014]\\s+', 'g');
const DASH = new RegExp('[\\u2013\\u2014]', 'g');
const clean = (s) =>
  (s ?? '').replace(INVISIBLE, '').replace(SPACED_DASH, ', ').replace(DASH, '-').replace(/\s+/g, ' ').trim();

// Same id rule as src/data/vocabulary.js.
const slug = (text) =>
  text
    .toLowerCase()
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

function umlaut(stem) {
  const au = stem.lastIndexOf('au');
  const last = Math.max(...['a', 'o', 'u', 'A', 'O', 'U'].map((v) => stem.lastIndexOf(v)));
  if (au >= 0 && au + 1 === last) return `${stem.slice(0, au)}äu${stem.slice(au + 2)}`;
  if (last < 0) return stem;
  const map = { a: 'ä', o: 'ö', u: 'ü', A: 'Ä', O: 'Ö', U: 'Ü' };
  return stem.slice(0, last) + map[stem[last]] + stem.slice(last + 1);
}

// "die Großstadt, -̈e" → { de: 'die Großstadt', plural: 'die Großstädte' }
function parseNoun(raw) {
  let de = clean(raw).replace(/\s*\(Pl\.\)$/, '');
  if (!/^(der|die|das|der\/die) /.test(de)) return { de, plural: null };
  const comma = de.indexOf(', ');
  if (comma < 0) return { de, plural: null };
  const head = de.slice(0, comma);
  const marker = de.slice(comma + 2).split(/[\s/]/)[0];
  const stem = head.replace(/^(der|die|das|der\/die) /, '');
  let plural = null;
  if (marker === '-') plural = stem;
  else if (marker.startsWith('-̈')) plural = umlaut(stem) + marker.slice(2);
  else if (marker.startsWith('-')) plural = stem + marker.slice(1);
  else if (/^\p{Lu}/u.test(marker)) plural = marker;
  return { de: head, plural: plural ? `die ${plural}` : null };
}

const own = new Set(WORDS.map((w) => w.id));
const rows = JSON.parse(readFileSync(source, 'utf8'))
  .map((w) => ({
    ...w,
    ...parseNoun(w.de),
    en: clean(w.en),
    example: clean(w.example),
    exampleEn: clean(w.example_en),
  }))
  .filter((w) => w.de && w.en && !w.de.includes('...'))
  .sort((a, b) => LEVEL_ORDER.indexOf(a.level) - LEVEL_ORDER.indexOf(b.level));

const inDeck = (w) =>
  DECK_LEVELS.includes(w.level) &&
  w.example &&
  w.exampleEn &&
  w.example !== w.de &&
  !SKIP_REGISTERS.has(w.register) &&
  !SKIP_TOPICS.has(w.category) &&
  !(w.level === 'C2' && SKIP_C2_TOPICS.has(w.category));

const seen = new Set(own);
const deck = Object.fromEntries(DECK_LEVELS.map((l) => [l, []]));
const dictionary = [];
for (const w of rows.filter(inDeck)) {
  const id = `w-${slug(w.de)}`;
  if (seen.has(id)) continue;
  seen.add(id);
  const extra = {};
  if (w.plural) extra.pl = w.plural;
  if (WORK_TOPICS.has(w.category)) extra.t = ['work'];
  deck[w.level].push([w.de, w.en, w.example, w.exampleEn, ...(Object.keys(extra).length ? [extra] : [])]);
}
for (const w of rows) {
  const id = `w-${slug(w.de)}`;
  if (seen.has(id)) continue;
  seen.add(id);
  dictionary.push(w.plural ? [w.de, w.en, w.plural] : [w.de, w.en]);
}

const line = (row) => `  ${JSON.stringify(row)},`;
const out = `// GENERATED by scripts/import-wordfeather.mjs. Do not edit by hand; rerun the script.
// Source: Wordfeather by Abdullah Butt, https://github.com/abdullahbutt/wordfeather
// License: CC BY-NC 4.0 (https://creativecommons.org/licenses/by-nc/4.0/), not MIT
// like the rest of this repo. Changes: selected and filtered for AchsoKumpel,
// plural markers expanded, work topics tagged. Non-commercial use only.

// Practised in Words mode. Row: [german, english, exampleDe, exampleEn, extra?]
export const WF_DECK = {
${DECK_LEVELS.map((l) => `  ${l}: [\n${deck[l].map((r) => `  ${line(r)}`).join('\n')}\n  ],`).join('\n')}
};

// Tap-to-translate only. Row: [german, english, plural?]
export const WF_DICTIONARY = [
${dictionary.map(line).join('\n')}
];
`;
const target = fileURLToPath(new URL('../src/data/wordfeather.js', import.meta.url));
writeFileSync(target, out);
console.log(
  'deck',
  Object.fromEntries(DECK_LEVELS.map((l) => [l, deck[l].length])),
  'dictionary',
  dictionary.length,
  `${Math.round(out.length / 1024)} KB`,
);
